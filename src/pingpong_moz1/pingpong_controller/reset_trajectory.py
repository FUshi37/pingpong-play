"""Independent bounded trajectory for supervised right-arm reset motion.

This module intentionally has no dependency on ``safety_limiter``.  Reset
commands are generated by a small velocity/acceleration bounded state machine
so returning to the initial pose cannot become a one-tick position jump.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np


@dataclass(frozen=True)
class ResetTrajectoryStatus:
    active: bool
    progress: float
    elapsed_s: float
    position_rad: np.ndarray
    velocity_rad_s: np.ndarray
    target_rad: np.ndarray


class SlowResetTrajectory:
    """Synchronized quintic S-curve reset with bounded speed/acceleration."""

    def __init__(
        self,
        *,
        dt_s: float,
        velocity_limit_deg_s: float | tuple[float, ...] = 15.0,
        acceleration_limit_deg_s2: float | tuple[float, ...] = 40.0,
        minimum_duration_s: float = 2.0,
        joints: int = 7,
    ) -> None:
        self.joints = int(joints)
        self.dt_s = float(dt_s)
        if not np.isfinite(self.dt_s) or self.dt_s <= 0.0:
            raise ValueError("reset trajectory dt_s must be positive")
        self.minimum_duration_s = float(minimum_duration_s)
        if (not np.isfinite(self.minimum_duration_s)
                or self.minimum_duration_s < 0.0):
            raise ValueError(
                "reset trajectory minimum_duration_s must be finite and "
                "non-negative")
        self.velocity_limit_rad_s = self._limits(
            velocity_limit_deg_s, "velocity_limit_deg_s")
        self.acceleration_limit_rad_s2 = self._limits(
            acceleration_limit_deg_s2, "acceleration_limit_deg_s2")
        self.velocity_limit_rad_s = np.deg2rad(
            self.velocity_limit_rad_s).astype(np.float64)
        self.acceleration_limit_rad_s2 = np.deg2rad(
            self.acceleration_limit_rad_s2).astype(np.float64)
        self.position_rad = np.zeros(self.joints, dtype=np.float64)
        self.velocity_rad_s = np.zeros(self.joints, dtype=np.float64)
        self.target_rad = self.position_rad.copy()
        self._start_rad = self.position_rad.copy()
        self._duration_s = np.zeros(self.joints, dtype=np.float64)
        self._initial_distance_rad = np.zeros(self.joints, dtype=np.float64)
        self.elapsed_s = 0.0
        self.active = False

    def _limits(self, value: object, name: str) -> np.ndarray:
        values = np.asarray(value, dtype=np.float64)
        if values.ndim == 0:
            values = np.full(self.joints, float(values), dtype=np.float64)
        values = values.reshape(-1)
        if (values.shape != (self.joints,)
                or not np.all(np.isfinite(values))
                or np.any(values <= 0.0)):
            raise ValueError(
                f"{name} must be positive finite scalar or {self.joints}-vector")
        return values

    def start(
        self,
        position_rad: object,
        target_rad: object,
        *,
        minimum_duration_s: float | None = None,
    ) -> None:
        position = np.asarray(position_rad, dtype=np.float64).reshape(self.joints)
        target = np.asarray(target_rad, dtype=np.float64).reshape(self.joints)
        if not np.all(np.isfinite(position)) or not np.all(np.isfinite(target)):
            raise ValueError("reset trajectory endpoints must be finite")
        segment_minimum_duration_s = (
            self.minimum_duration_s
            if minimum_duration_s is None
            else float(minimum_duration_s)
        )
        if (not np.isfinite(segment_minimum_duration_s)
                or segment_minimum_duration_s < 0.0):
            raise ValueError(
                "reset trajectory segment minimum_duration_s must be finite "
                "and non-negative")
        self.position_rad = position.copy()
        self.velocity_rad_s.fill(0.0)
        self.target_rad = target.copy()
        self._start_rad = position.copy()
        self._initial_distance_rad = np.abs(target - position)
        # For s(u)=10u^3-15u^4+6u^5, max(ds/du)=1.875 and
        # max(abs(d2s/du2))=10/sqrt(3)=5.7735026919.  Choose one shared
        # duration from the most restrictive joint and both analytic extrema.
        # This guarantees the configured continuous speed/acceleration limits,
        # keeps the arm coordinated, and prevents a small-angle joint from
        # snapping to its reset value before the rest of the arm.
        duration_for_velocity = (
            1.875 * self._initial_distance_rad
            / self.velocity_limit_rad_s)
        duration_for_acceleration = np.sqrt(
            (10.0 / np.sqrt(3.0)) * self._initial_distance_rad
            / self.acceleration_limit_rad_s2)
        moving = self._initial_distance_rad > 1e-7
        self._duration_s.fill(0.0)
        if np.any(moving):
            required_duration_s = np.maximum(
                duration_for_velocity, duration_for_acceleration)
            shared_duration_s = max(
                segment_minimum_duration_s,
                float(np.max(required_duration_s[moving])),
            )
            self._duration_s[moving] = shared_duration_s
        self.elapsed_s = 0.0
        self.active = bool(np.any(moving))

    def step(self) -> tuple[np.ndarray, np.ndarray, bool]:
        if not self.active:
            self.position_rad = self.target_rad.copy()
            self.velocity_rad_s.fill(0.0)
            return self.position_rad.copy(), self.velocity_rad_s.copy(), True

        self.elapsed_s += self.dt_s
        moving = self._duration_s > 0.0
        phase = np.ones(self.joints, dtype=np.float64)
        phase[moving] = np.clip(
            self.elapsed_s / self._duration_s[moving], 0.0, 1.0)
        phase2 = phase * phase
        phase3 = phase2 * phase
        phase4 = phase3 * phase
        phase5 = phase4 * phase
        blend = 10.0 * phase3 - 15.0 * phase4 + 6.0 * phase5
        blend_rate = 30.0 * phase2 - 60.0 * phase3 + 30.0 * phase4
        displacement = self.target_rad - self._start_rad
        self.position_rad = self._start_rad + displacement * blend
        self.velocity_rad_s.fill(0.0)
        self.velocity_rad_s[moving] = (
            displacement[moving] * blend_rate[moving]
            / self._duration_s[moving])
        # Account for binary accumulation of the fixed control period so a
        # nominal 2.000 s trajectory does not require an unintended 2.005 s
        # final tick.
        done = bool(
            self.elapsed_s + 1e-12 >= float(np.max(self._duration_s)))
        if done:
            self.position_rad = self.target_rad.copy()
            self.velocity_rad_s.fill(0.0)
            self.active = False
        return (
            self.position_rad.copy(),
            self.velocity_rad_s.copy(),
            done,
        )

    def status(self) -> ResetTrajectoryStatus:
        if not np.any(self._initial_distance_rad > 1e-12):
            progress = 1.0
        else:
            ratios = np.divide(
                np.abs(self.target_rad - self.position_rad),
                self._initial_distance_rad,
                out=np.zeros_like(self._initial_distance_rad),
                where=self._initial_distance_rad > 1e-12,
            )
            progress = float(np.clip(1.0 - np.max(ratios), 0.0, 1.0))
        return ResetTrajectoryStatus(
            active=bool(self.active),
            progress=progress,
            elapsed_s=float(self.elapsed_s),
            position_rad=self.position_rad.copy(),
            velocity_rad_s=self.velocity_rad_s.copy(),
            target_rad=self.target_rad.copy(),
        )
